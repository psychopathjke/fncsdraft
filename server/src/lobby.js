/* Лобби командной карьеры: арбитр порядка.
 *
 * Здесь НЕТ ни одной строки симуляции и быть не должно. Сервер решает только
 * два вопроса: кто уже готов и в каком порядке пришли решения. Вечер считает
 * каждый браузер сам — это измерено (tools/check-lockstep.js), и на этом
 * стоит весь режим.
 *
 * Ни Workers API, ни fetch: поэтому машина проверяется обычным node за
 * секунду, а worker.js остаётся тонким переходником.
 */
'use strict';

/* Сколько человек пускает лобби. Командная карьера — двое и только двое:
   локстеп написан на пару. Гонка карьер общего счёта не ведёт, там людей
   может быть больше — шестеро; дальше таблица «кто впереди» перестаёт
   читаться с одного взгляда, а лобби начинает возить шесть сводок на каждый
   прожитый день. См. join и CC_RACE_MAX на клиенте. */
const RACE_MAX=6;

function createLobby(opts){
  const o=opts||{};
  const st={
    build:o.build||null,
    seed:o.seed||('team-'+Math.random().toString(36).slice(2,10)),
    team:o.team||{},
    cards:{},            // id -> ночная карточка
    ready:{},            // id -> день, на который заявлена готовность
    feed:[],             // нумерованная лента решений текущего вечера
    n:0,                 // последний выданный номер
    evening:null,        // {seed, n} пока вечер идёт
    digests:{},          // id -> {hash, team}
    last:null,           // {team, n} последнего закрытия — для того, кто закрытие не получил
    div:o.div||null,     // дивизион команды: с ним сверяется каждый входящий
    seen:0,              // когда лобби трогали в последний раз
    over:false,          // дуо разорвано
    race:false           // лобби гонки: людей больше двух, дивизион не сверяется
  };
  const ids=()=>Object.keys(st.cards);
  const peerOf=id=>ids().find(x=>x!==id)||null;
  // Сколько готовых нужно для старта: команда — ровно двое; гонка — все, кто в
  // комнате (от двух до RACE_MAX): общая комната гонки на N человек.
  const need=()=>st.race ? Math.max(2, ids().length) : 2;
  /* Состояние несёт и ВЕЧЕР: идёт ли он (сид, номер, день) и вся его лента.
     Вкладка, перезагруженная посреди вечера, приходит с пустой памятью — по
     этому она понимает, что вечер есть, и догоняет его по своим же ответам
     (см. ccMpResume). Кому вечер не нужен, тот ленту просто не читает. */
  const stateMsg=id=>({t:'state', team:st.team, seed:st.seed,
                       peer:st.cards[peerOf(id)]||null,
                       evening:st.evening||null,
                       feed:st.evening ? st.feed.slice() : [],
                       closed:st.last||null});

  return {
    get state(){ return st; },

    join(id, msg){
      if(st.over) return [{to:'self', msg:{t:'bye', reason:'over'}}];
      /* Версия сверяется ДО всего остального: пустить клиента с чужим кодом
         значит согласиться на молчаливое расхождение в середине вечера.

         Но сказать надо ОБОИМ. Раньше отказ получал только пришедший, и на
         экране у него стояло «обновите страницу» — а обновлять надо было
         второму, который сидел в лобби со старой сборкой и ни о чём не знал.
         Теперь ему летит 'stale', и он перезагружается сам. Две стороны
         сходятся на свежей сборке без единого нажатия.

         Свою версию отказ несёт с собой: без неё игрок видит «разные версии»
         и не знает, чья именно чужая. */
      if(st.build && msg && msg.build!==st.build)
        return [{to:'self', msg:{t:'bye', reason:'build', have:st.build, got:msg.build}},
                {to:'peer', msg:{t:'stale', build:msg.build, have:st.build}}];
      /* ЧУЖОЙ ДИВИЗИОН НЕ ВХОДИТ ВОВСЕ.

         Его слово, 29 августа: «запретить присоединяться, когда 1 и 5 див,
         чтоб даже в лобби не пускало». Клиент это уже ловил — но ПОСЛЕ входа:
         сокет открывался, приезжало состояние, и только тогда карьера
         откатывалась назад (см. ccMpStateOk). То есть на секунду двое всё-таки
         оказывались в одной команде, и у создателя мигала чужая карточка.

         Здесь отказ до всего: пришедший не попадает в st.cards, напарник о нём
         не узнаёт, лобби остаётся таким, каким было. Свой же входит всегда —
         сид лобби у него совпал (st.seed), а дивизион мог разойтись из-за
         повышения, которое он ещё не дочитал. */
      /* ГОНКА — ЛОББИ ДРУГОЙ ПОРОДЫ, и это решается здесь, на входе.

         Его вопрос 4 сентября: «а можно больше игроков сделать одновременно?».
         Командная карьера — ровно двое: весь вечер стоит на локстепе, где двое
         считают один прогон и сверяют каждый бросок; третьему в нём места нет.
         А гонка не считает ничего общего — у каждого своя карьера, ездит одна
         сводка, — поэтому в ней людей может быть сколько угодно в пределах
         разумного. Отсюда два порога вместо одного.

         Дивизион в гонке тоже не сверяется: сойтись должны хоть первый с
         пятым, в этом её смысл. Комната помечается гонкой первым же вошедшим
         (msg.race) и остаётся ею — командный клиент в неё не попадёт, потому
         что кода он не знает. */
      if(msg && msg.race) st.race=true;
      const own=msg && msg.seed && st.seed && msg.seed===st.seed;
      if(!st.race && !own && st.div && msg && msg.div && msg.div!==st.div)
        return [{to:'self', msg:{t:'bye', reason:'div', have:st.div, got:msg.div}}];
      if(!st.race && msg && msg.div && !st.div) st.div=msg.div;
      if(ids().length>=(st.race ? RACE_MAX : 2) && !st.cards[id])
        return [{to:'self', msg:{t:'bye', reason:'full'}}];
      st.cards[id]=(msg&&msg.card)||null;
      const out=[{to:'self', msg:stateMsg(id)}];
      const p=peerOf(id);
      if(p) out.push({to:'peer', msg:{t:'card', card:st.cards[id], by:id}});
      return out;
    },

    card(id, card){
      st.cards[id]=card;
      return [{to:'peer', msg:{t:'card', card:card, by:id}}];
    },

    /* Состояние команды, изменённое одним из двоих, — сразу второму.
     *
     * Его отчёт, 26 августа: «выбрал спот, у тимейта не показывается сразу».
     * Клиент слал сюда {t:'team'} с самого начала, а разбирать его было
     * некому — состояние доезжало только при входе (state) и в конце вечера
     * (close). Между ними двое сидели с разными метками на карте.
     *
     * Сервер по-прежнему ничего не считает: он кладёт присланное к себе и
     * пересказывает напарнику. Кто прислал последним, того и состояние —
     * тот же порядок прихода, что решает расхождение в digest. */
    team(id, t){
      if(!t) return [];
      st.team=t;
      // Команда поднялась или упала — лобби запоминает новый дивизион, иначе
      // вернувшийся после повышения получил бы отказ по собственной команде.
      if(t.division) st.div=t.division;
      return [{to:'peer', msg:{t:'team', team:st.team, by:id}}];
    },

    /* Сколько человек уже нажали «играть» — счёт ведёт сервер.

       Его слово, 27 августа: «нужно, чтоб при нажатие кнопки играть было
       написано 1/2 если жмет кто-то или 0/2, игра начинается если нажмут два
       человека». Считать это на клиенте нечем: свою готовность он знает, а
       чужую — только со слов сервера, и после обрыва у него не осталось бы
       ничего. Здесь готовность лежит и так.

       Число едет полем `ready`, а не `n`: `n` в этом протоколе — номер
       события, по нему клиент догоняет пропущенное после обрыва (см. since).
       Положить в него счётчик значило бы сдвинуть клиенту метку прочитанного.

       Знаменатель всегда 2, а не число подключённых: команда — это двое, и
       пока второй не вошёл, честный ответ «1 из 2», а не «1 из 1». */
    ready(id, day, kind){
      /* Вечер этого дня уже идёт — это переподключение или перезагрузка
         посреди вечера. Старт тот же, с тем же сидом, и только ему:
         напарник его уже получил и считает. */
      if(st.evening && st.evening.day===day){
        /* Кто уже заявлял готовность в ЭТОТ вечер и заявляет снова — жмёт
           «играть» заново (вечер завис, оба вернулись). Первому — догон, а
           когда заново готовы оба — вечер заводится с чистого листа: старая
           лента застрявшего вечера никому не нужна. */
        st.evening.readied=st.evening.readied||{};
        const again=!!st.evening.readied[id];
        st.evening.readied[id]=true;
        if(again){
          st.ready[id]=day;
          const all2=ids();
          if(all2.length>=need() && all2.every(x=>st.ready[x]===day)){
            st.ready={}; st.feed=[]; st.digests={};
            st.evening={seed:st.seed+'|'+day+'|'+(++st.n), n:st.n, day:day, readied:{}};
            all2.forEach(x=>{ st.evening.readied[x]=true; });
            return [{to:'all', msg:{t:'start', seed:st.evening.seed, n:st.evening.n, day:day, fresh:true}}];
          }
        }
        return [{to:'self', msg:{t:'start', seed:st.evening.seed, n:st.evening.n, day:day, resume:true}}];
      }
      // Готовность на ДРУГОЙ день при идущем вечере: тот вечер брошен, команда ушла дальше.
      if(st.evening && st.evening.day!==day){ st.evening=null; st.feed=[]; st.digests={}; }
      st.ready[id]=day;
      /* ВИД вечера — тоже. Его скрин 29 августа, 11 января: один нажал Solo
         Series, второй — открытый квал Reload того же дня, лобби завело вечер
         на двоих, и они считали два разных турнира с первой игры («field
         …m2.58.n4900 vs …r1.15.n900»). День совпал — этого мало. Клиент без
         вида (старая сборка) считается согласным на что угодно. */
      st.kinds=st.kinds||{};
      if(kind) st.kinds[id]=kind; else delete st.kinds[id];
      const all=ids();
      const both=all.length>=need() && all.every(x=>st.ready[x]===day);
      const n=all.filter(x=>st.ready[x]===day).length;
      if(!both) return [{to:'all', msg:{t:'ready', by:id, day:day, ready:n, of:need()}}];
      const named=all.filter(x=>st.kinds[x]);
      if(named.length>=2 && named.some(x=>st.kinds[x]!==st.kinds[named[0]])){
        // Разные турниры — старта нет, и готовность снимается с обоих: пусть
        // договорятся и нажмут заново одно и то же.
        const clash={}; all.forEach(x=>{ clash[x]=st.kinds[x]; });
        st.ready={}; st.kinds={};
        return [{to:'all', msg:{t:'ready', by:id, day:day, ready:0, of:need(), clash:clash}}];
      }
      /* Смесь сборок: у одного вид есть, у другого нет. «Без вида — согласен
         на всё» пропускало старую вкладку в вечер с новым календарём, и пара
         опять считала два разных турнира с первой игры (его страница «баги»,
         скрины 8-9, 31 августа, 4179a04f: соло-квал n4900 против дуо Victory
         Cup n2450 в один день; игрок в ЛС — «duo vcc против ewc»). Старта
         нет: новому клиенту в clash приезжает пустой вид напарника — он
         объяснит про старую версию; старый увидит сброс готовности. Пара из
         ДВУХ вкладок без вида консистентна между собой — её не трогаем. */
      if(named.length>0 && named.length<all.length){
        const clash={}; all.forEach(x=>{ clash[x]=st.kinds[x]||''; });
        st.ready={}; st.kinds={};
        return [{to:'all', msg:{t:'ready', by:id, day:day, ready:0, of:need(), clash:clash}}];
      }
      st.kinds={};
      st.ready={};
      st.feed=[]; st.digests={};
      st.evening={seed:st.seed+'|'+day, n:++st.n, day:day, readied:{}};
      all.forEach(x=>{ st.evening.readied[x]=true; });
      return [{to:'all', msg:{t:'start', seed:st.evening.seed, n:st.evening.n, day:day}}];
    },

    act(id, kind, payload){
      const e={t:'act', n:++st.n, kind:kind, payload:payload, by:id};
      st.feed.push(e);
      return [{to:'all', msg:e}];
    },

    // Догон после обрыва: всё, что случилось после названного номера.
    since(id, n){ return st.feed.filter(e=>e.n>n); },

    /* Расхождение решается ПОРЯДКОМ ПРИХОДА, а не спором и не часами.

       Часов здесь нет нарочно: Date.now() в машине состояний сделал бы её
       непроверяемой, а порядок прихода — это порядок вызовов, он и так
       нумеруется. Первый пришедший хеш и становится истиной: у игрока на
       экране обязано оказаться то же, что у напарника, и любой другой ответ
       означал бы, что один из двоих доигрывает вечер, которого не было. */
    digest(id, hash, team){
      if(!st.digests[id]) st.digests[id]={hash:hash, team:team, seq:++st.n};
      const all=ids();
      if(!all.every(x=>st.digests[x])) return [{to:'peer', msg:{t:'digest', by:id}}];
      // На N человек (гонка): победитель — самый ранний, «сошлось» — когда хеш у всех один.
      const win=all.slice().sort((a,b)=>st.digests[a].seq-st.digests[b].seq)[0];
      const same=all.every(x=>st.digests[x].hash===st.digests[all[0]].hash);
      st.team=st.digests[win].team||st.team;
      st.last={team:st.team, n:st.n};
      st.evening=null; st.feed=[]; st.digests={};
      const msg={t:'close', team:st.team};
      if(!same) msg.split=true;
      return [{to:'all', msg:msg}];
    },

    part(id){
      st.over=true;
      return [{to:'all', msg:{t:'bye', reason:'part', by:id||null}}];
    },

    /* Часы приходят СНАРУЖИ, а не берутся из Date.now().

       Иначе срок жизни лобби нельзя было бы проверить, не подкручивая
       системное время, — а вся ценность этой машины в том, что она
       проверяется обычным node за секунду. Настоящие часы подставляет
       worker.js, который и так живёт в мире побочных эффектов. */
    touch(atMs){ st.seen=atMs||0; },
    stale(atMs, ttlMs){ return (atMs-st.seen) >= ttlMs; }
  };
}

module.exports={ createLobby };
