// Капы, выплаты и Grand Royale 2021-го из tools/measured/tracker-2021.json и liqui-2021/
// (финалы Grand Royale у NA East / West — на Tracker пусто). Выход — tools/2021-cal.generated.js:
// CC_VICTORY_2021, CC_DCC_PAY_2021, CC_MAJOR_PAY_2021 (1–4 — сезоны, 5 — Grand Royale), GR2021_TRIOS.
//   node tools/build-2021-cal.js
'use strict';
const fs = require('fs'), path = require('path');
const M = path.join(__dirname, 'measured');
const H = JSON.parse(fs.readFileSync(path.join(M, 'tracker-2021.json'), 'utf8'));
const REGS = ['EU', 'NAC', 'NAW', 'BR', 'ASIA', 'ME', 'OCE'];
const src = r => r === 'NAC' ? 'NAE' : r;
const table = usd => usd.slice().sort((a, b) => a[0] - b[0]);
const obj = o => JSON.stringify(o).replace(/"(\w+)":/g, '$1:');
const out = [];
// ---- капы (дни — Европа): трио Cash Cup и Solo Cash Cup ----
const V = [];
[['S15'], ['S16'], ['S17'], ['S18']].forEach(([s]) => {
  [['CashCup', 'trio', 'Trios Cash Cup', s], ['SoloCashCup', 'solo', 'Solo Cash Cup', s + 'SOLO']].forEach(([slug, mode, name, pay]) => {
    const seen = new Set();
    (H[s + '_' + slug + '|EU'] || []).forEach(w => { if (seen.has(w.begin)) return; seen.add(w.begin); V.push({ day: w.begin, id: s + '_' + slug, mode, n: 0, name, pay }); });
  });
});
// Кап в вечер FNCS карьеры не нужен (один турнир в день): дни календаря — tools/career-2021-cal.js.
const calText = fs.readFileSync(path.join(__dirname, 'career-2021-cal.js'), 'utf8');
const busy = [...calText.matchAll(/\['(\d{4}-\d\d-\d\d)','(\d{4}-\d\d-\d\d)','[^']+','(major|nations)'\]/g)].map(m => [m[1], m[2]]);
for (let i = V.length - 1; i >= 0; i--) if (busy.some(([a, b]) => V[i].day >= a && V[i].day <= b)) V.splice(i, 1);
V.sort((a, b) => a.day < b.day ? -1 : a.day > b.day ? 1 : 0);
const seq = {}; V.forEach(v => { seq[v.id] = (seq[v.id] || 0) + 1; v.n = seq[v.id]; });
out.push('const CC_VICTORY_2021=[');
out.push(V.map(v => '  ' + JSON.stringify(v).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'")).join(',\n'));
out.push('];');
// ---- выплаты капов по сезону и региону (на игрока) ----
const dcc = {};
const payOf = (key) => { const w = (H[key] || []).find(x => x.usd && x.usd.length); return w ? table(w.usd) : null; };
['S15', 'S16', 'S17', 'S18'].forEach(s => {
  dcc[s] = {}; dcc[s + 'SOLO'] = {};
  REGS.forEach(r => {
    const d = payOf(s + '_CashCup|' + src(r)); if (d) dcc[s][r] = d;
    const o = payOf(s + '_SoloCashCup|' + src(r)); if (o) dcc[s + 'SOLO'][r] = o;
  });
});
out.push('const CC_DCC_PAY_2021=' + obj(dcc) + ';');
// ---- финалы сезонов и Grand Royale (на игрока) ----
const maj = {};
const finKey = (s, reg) => [s + '_FNCS_Finals|' + reg + '|Finals_Round2', s + '_FNCS_GrandFinals|' + reg + '|GrandFinals_Round2'].find(k => H[k] && H[k].usd && H[k].usd.length);
[[1, 'S15'], [2, 'S16'], [3, 'S17'], [4, 'S18']].forEach(([n, s]) => {
  maj[n] = {};
  REGS.forEach(r => { const k = finKey(s, src(r)); if (k) maj[n][r] = table(H[k].usd); });
});
maj[5] = {};
REGS.forEach(r => { const b = H['S18_GrandRoyale_Finals|' + src(r) + '|Finals_Round2']; if (b && b.usd && b.usd.length) maj[5][r] = table(b.usd); });
out.push('const CC_MAJOR_PAY_2021=' + obj(maj) + ';');
// ---- Grand Royale: настоящие трио финала по регионам ----
const LIQ = { NAE: 'North America East', NAW: 'North America West' };
const gr = {};
REGS.forEach(r => {
  const by = new Map();
  ['Finals_Round1', 'Finals_Round2'].forEach(w => ((H['S18_GrandRoyale_Finals|' + src(r) + '|' + w] || {}).rows || []).forEach(row => {
    const k = row[6].map(x => String(x).toLowerCase()).sort().join('|');
    by.set(k, { names: row[6], pts: (by.has(k) ? by.get(k).pts : 0) + row[1] });
  }));
  let list = [...by.values()].sort((a, b) => b.pts - a.pts).map(x => x.names);
  if (!list.length && LIQ[src(r)]) {
    const f = path.join(M, 'liqui-2021', 'Fortnite Champion Series__2021__Grand Royale__' + LIQ[src(r)] + '.txt');
    if (fs.existsSync(f)) {
      const t = fs.readFileSync(f, 'utf8'); const re = /\{\{prize pool slot( trios?)?\s*\|([^}]*)\}\}/g; let m;
      const rows = [];
      while ((m = re.exec(t))) { const p = m[2].split('|').map(x => x.trim()); const place = +((p.find(x => /^place=/.test(x)) || '').split('=')[1] || 0); const names = p.filter(x => x && !/=/.test(x)).slice(0, 3); if (place && names.length === 3) rows.push([place, names]); }
      list = rows.sort((a, b) => a[0] - b[0]).map(x => x[1]);
    }
  }
  gr[r] = list;
});
out.push('const GR2021_TRIOS=' + JSON.stringify(gr) + ';');
fs.writeFileSync(path.join(__dirname, '2021-cal.generated.js'), '// Generated by tools/build-2021-cal.js — капы, выплаты и Grand Royale FNCS 2021.\n' + out.join('\n') + '\n');
console.log('cups', V.length, 'dcc', Object.keys(dcc).map(k => k + ':' + Object.keys(dcc[k]).length).join(' '), 'majors', Object.keys(maj).map(n => n + ':' + Object.keys(maj[n]).length).join(' '), 'GR', Object.keys(gr).map(r => r + ':' + gr[r].length).join(' '), 'EU1', JSON.stringify((maj[1].EU || []).slice(0, 2)), 'GR EU1', JSON.stringify((maj[5].EU || []).slice(0, 2)));
