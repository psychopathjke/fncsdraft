// Японские ники схлопывались в одну «пару».
//
// Проба брала ключ пары через _gcNorm, а тот выбрасывает всё, кроме латиницы и
// цифр (`[^a-z0-9]`). У японских ников после этого не остаётся НИЧЕГО, и ключ у
// всех выходил один и тот же — «+». Отчёт показывал три разные японские пары
// как одну «пару в трёх регионах»: ложная тревога ровно того вида, который эта
// проба и должна отличать от настоящей смены региона.
//
// Ключ теперь падает на сам ник в нижнем регистре, когда после нормализации
// пусто. _gcNorm не тронут: он нужен таким, какой есть, для сверки с Liquipedia.
const fs=require('fs'), path=require('path');
const F=path.join(__dirname,'check-card-pairs.js');
let s=fs.readFileSync(F,'utf8');
const A="'          var key = hs.map(function(h){ return _gcNorm(h); }).sort().join(\"+\");',";
if(s.split(A).length!==2) throw new Error('строка ключа пары не найдена ровно один раз');
s=s.replace(A,
"'          // Ник без латиницы (японские составы) после _gcNorm пуст, и ключи',\n" +
"'          // всех таких пар совпадали. Пусто — берём сам ник.',\n" +
"'          var key = hs.map(function(h){ return _gcNorm(h) || String(h).toLowerCase(); }).sort().join(\"+\");',");
fs.writeFileSync(F,s);
