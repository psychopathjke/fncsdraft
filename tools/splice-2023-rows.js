// Вклеивает сгенерированные данные 2023-го в index.html:
//   tools/2023-rows.generated.js — строки карточек, перед строками 2024-го;
//   tools/2023-cal.generated.js  — капы и выплаты, между маркерами «FNCS 2023 cal».
// Повторный запуск заменяет прошлую вклейку (между маркерами).
//   node tools/splice-2023-rows.js
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const file = path.join(ROOT, 'index.html');
let s = fs.readFileSync(file, 'utf8');
const nl = s.includes('\r\n') ? '\r\n' : '\n';
const read = f => fs.readFileSync(path.join(__dirname, f), 'utf8').replace(/\r?\n$/, '').split(/\r?\n/).join(nl);
function splice(A, B, body, fallbackBefore) {
  const block = A + nl + body + nl + B;
  const i = s.indexOf(A), j = s.indexOf(B);
  if (i >= 0 && j > i) { s = s.slice(0, i) + block + s.slice(j + B.length); return; }
  const at = s.indexOf(fallbackBefore);
  if (at < 0) throw new Error('marker not found: ' + fallbackBefore);
  s = s.slice(0, at) + block + nl + s.slice(at);
}
const rows = read('2023-rows.generated.js');
splice('// ==== FNCS 2023 rows (tools/splice-2023-rows.js) ====', '// ==== /FNCS 2023 rows ====', rows, '// Generated by tools/build-2024-rows.js');
const cal = read('2023-cal.generated.js');
splice('// ==== FNCS 2023 cal (tools/splice-2023-rows.js) ====', '// ==== /FNCS 2023 cal ====', cal, '/* ---- FNCS 2024 в карьере');
fs.writeFileSync(file, s);
console.log('spliced rows', rows.length, 'cal', cal.length);
