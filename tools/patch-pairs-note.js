// Отчёт сам говорит, где улика слабая.
//
// Пара считается одной и той же по НОРМАЛИЗОВАННЫМ никам, а нормализация
// выбрасывает всё, кроме латиницы: «skyǃ» и «Sky» после неё одно слово, хотя по
// его же решению это разные люди (полноширинное восклицание — обычный приём
// тёзки). Раз ключ такой нужен (регистр и теги клубов меняются), пусть отчёт
// отличает случаи буквального совпадения ников от тех, где совпал только
// огрызок: первое — смена региона, второе почти всегда тёзки.
const fs=require('fs'), path=require('path');
const F=path.join(__dirname,'check-card-pairs.js');
let s=fs.readFileSync(F,'utf8');
const A="    g.forEach(s => console.log('      ' + s.set + ' ' + s.reg + '   ' + s.who));";
if(s.split(A).length!==2) throw new Error('строка печати не найдена ровно один раз');
s=s.replace(A, [
  A,
  "    const raw = new Set(g.map(s => s.who.replace(/ \d+| \?/g, '')));",
  "    if (raw.size > 1) console.log('      ↑ ники совпадают только после нормализации — скорее тёзки, а не смена региона');"
].join('\n'));
fs.writeFileSync(F,s);
