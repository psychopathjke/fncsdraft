// Turns the Global Championship field on Liquipedia into a nationality table for
// index.html.
//
//   node tools/build-gc2025-nat.js > tools/gc2025-nat.generated.js
//
// Tracker gives one flag per team, which is often a team-mate's, and that is what
// most 2025 cards currently carry. Liquipedia gives a country per player, checked
// by editors, for all ninety-nine players who reached Lyon -- the strongest names
// in the set, and exactly the ones a wrong flag is most visible on.
//
// Country names arrive in English and the cards carry Russian ones, so the map
// between them is taken from the page's own CC_EN / CC_RU tables rather than
// written out again here.
const fs = require('fs'), path = require('path');

const ROOT = path.resolve(__dirname, '..');
const HOME = process.env.USERPROFILE || process.env.HOME;
const SRC = path.join(HOME, 'Desktop', 'GLOBAL 2025', 'gc2025-qualification.json');

const html = fs.readFileSync(path.join(ROOT, 'index.html'), 'utf8');

// Every CC_RU / CC_EN declaration, merged the way the page merges them.
function tables(prefix) {
  const out = {};
  for (const m of html.matchAll(new RegExp('const (' + prefix + '[A-Z_0-9]*)=', 'g'))) {
    const at = html.indexOf('const ' + m[1] + '=');
    let i = html.indexOf('{', at), d = 0, q = null, esc = false, end = -1;
    for (let j = i; j < html.length; j++) {
      const c = html[j];
      if (q) { if (esc) esc = false; else if (c === '\\') esc = true; else if (c === q) q = null; continue; }
      if (c === '"' || c === "'") q = c; else if (c === '{') d++;
      else if (c === '}') { d--; if (!d) { end = j + 1; break; } }
    }
    const body = html.slice(i, end);
    for (const kv of body.matchAll(/["']?([a-z]{2})["']?\s*:\s*["']([^"']+)["']/g)) {
      if (out[kv[1]] === undefined) out[kv[1]] = kv[2];
    }
  }
  return out;
}
const CC_RU = tables('CC_RU'), CC_EN = tables('CC_EN');
const codeOf = {};
Object.keys(CC_EN).forEach(code => { codeOf[CC_EN[code].toLowerCase()] = code; });

const field = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const nat = {}, missing = new Set();
let players = 0;
Object.keys(field).forEach(route => {
  field[route].forEach(team => team.forEach(p => {
    players++;
    if (!p.c) return;
    const code = codeOf[p.c.toLowerCase()];
    if (!code) { missing.add(p.c); return; }
    const ru = CC_RU[code];
    if (!ru) { missing.add(p.c + ' (' + code + ', no Russian name)'); return; }
    nat[p.n] = ru;
  }));
});

const q = s => JSON.stringify(String(s));
console.log('// Generated by tools/build-gc2025-nat.js from the Liquipedia field of the');
console.log('// FNCS 2025 Global Championship. One country per player, editor-checked,');
console.log('// against Tracker\'s one flag per team.');
console.log('const GC2025_NAT={');
console.log(Object.keys(nat).sort().map(h => '  ' + q(h) + ':' + q(nat[h])).join(',\n'));
console.log('};');

console.error('players seen      : ' + players);
console.error('nationalities out : ' + Object.keys(nat).length);
console.error('countries unmapped: ' + missing.size + (missing.size ? ' -> ' + [...missing].join(', ') : ''));
