// Урон в минуту: время в живых считается ПЕРВЫМ, и урон растёт от него.
//
// Сторож check-matchstats-real держал одну красную строку: лидер дня по урону
// в минуту выходил 56.7 против 41.28 у Кинча (×1.37), хотя лидер по самому
// урону сходился (×1.07) и время в живых сходилось (×1.04). Причина
// арифметическая, а не балансная: урон и время брались из ДВУХ независимых
// бросков (surv*srnd(8,11) и 55+surv*srnd(960,1180)), а максимум отношения по
// лобби растёт от независимого шума в знаменателе. У Кинча лидер по урону и
// лидер по урону в минуту — один человек: 4128 за ровно 100 минут = 41.28.
//
// Поэтому время в живых теперь считается до урона, а число попаданий берётся
// из самих минут: столько, сколько человек простоял в файтах. Знаменатель
// перестал быть отдельным случаем — и максимум отношения снова приходится на
// того, кто больше всех нанёс.
const fs=require('fs'), path=require('path');
const F=path.join(__dirname,'..','index.html');
let s=fs.readFileSync(F,'utf8');
const NL=s.indexOf('\r\n')>=0?'\r\n':'\n';

// 1) Время в живых и шторм — до броска урона.
const aliveBlock=[
'  const alive = Math.round(55 + surv*srnd(960,1180));',
'  /* Время в шторме: у Кинча лидер дня провёл в нём 47:03 при сотне минут',
'     в живых — то есть почти половину. У нас стояло от пяти до двадцати',
'     процентов, и за день выходило 927 секунд против его 2 823. */',
'  const storm = Math.round(alive*srnd(0.22,0.62));'
].join(NL);
if(s.split(aliveBlock).length!==2) throw new Error('блок времени в живых не найден ровно один раз');
s=s.replace(aliveBlock+NL, '');

const hitsLine='  const hits = Math.round(elims*srnd(3.9,4.6) + surv*size*srnd(8,11) + srnd(1,2));';
if(s.split(hitsLine).length!==2) throw new Error('строка hits не найдена ровно один раз');
s=s.replace(hitsLine, [
  aliveBlock,
  '  const mins = alive/60;',
  '  /* Попадания идут от МИНУТ, а не от отдельного броска: файты случаются во',
  '     времени. Иначе урон и время — два независимых случая, и максимум их',
  '     отношения по лобби улетает выше настоящего лидера (см. patch-dpm.js). */',
  '  const hits = Math.round(elims*srnd(4.0,4.5) + mins*size*srnd(0.50,0.60) + srnd(1,2));'
].join(NL));

// 2) Сложение времени остаётся на своём месте, объявления там уже нет.
const sumLine='  s.timeAlive += alive; s.inStorm += storm;';
if(s.split(sumLine).length!==2) throw new Error('строка сложения времени не найдена');
fs.writeFileSync(F,s);
