// Страна игрока из уже скачанных страниц Liquipedia — для карточек, у которых Tracker страны не
// отдал (countryCode пустой у трети записей). Источники без новых запросов:
//   • кэш build-year-orgs.js (%TEMP%/liqui-orgs/*.json — отрендеренный HTML: флаг — картинка
//     «Gb-eng_hd.png» перед ником);
//   • сохранённый wikitext годов (tools/measured/liqui-20xx/*.txt: слоты «ник |flag1p1=de»).
// Коды — как у флагов режима (flags/w20/<код>.png); «uk» → «gb». Первое вхождение ника — его.
// Выход — tools/liqui-flags.generated.js: const NAT_LIQUI={ник в нижнем регистре: код}.
//   node tools/build-liqui-flags.js
'use strict';
const fs = require('fs'), os = require('os'), path = require('path');
const ROOT = path.resolve(__dirname, '..');
const have = new Set(fs.readdirSync(path.join(ROOT, 'flags', 'w20')).map(f => f.replace(/\.png$/, '')));
const SAME = { uk: 'gb', en: 'gb-eng', sc: 'gb-sct', wa: 'gb-wls' };
const norm = c => { c = String(c || '').toLowerCase().trim(); c = SAME[c] || c; return have.has(c) ? c : null; };
const out = {};
const put = (h, c) => { const k = String(h || '').toLowerCase().trim(); const v = norm(c); if (k && v && !out[k]) out[k] = v; };
// 1) отрендеренный HTML
const cache = path.join(os.tmpdir(), 'liqui-orgs');
if (fs.existsSync(cache)) for (const f of fs.readdirSync(cache)) {
  let h; try { h = JSON.parse(fs.readFileSync(path.join(cache, f), 'utf8')).parse.text['*']; } catch (e) { continue; }
  const re = /<span class="flag"><img[^>]*src="[^"]*\/([A-Za-z-]+)_hd\.png[^"]*"[^>]*><\/span><span class="name"[^>]*>(?:<a [^>]*>)?([^<]+)</g; let m;
  while ((m = re.exec(h))) put(m[2], m[1]);
}
// 2) wikitext годов
for (const dir of fs.readdirSync(path.join(__dirname, 'measured')).filter(d => /^liqui-20\d\d$/.test(d))) {
  for (const f of fs.readdirSync(path.join(__dirname, 'measured', dir))) {
    const t = fs.readFileSync(path.join(__dirname, 'measured', dir, f), 'utf8');
    const re = /\{\{prize pool slot[^|]*\|([^}]*)\}\}/g; let m;
    while ((m = re.exec(t))) {
      let last = null;
      m[1].split('|').map(x => x.trim()).forEach(x => {
        if (!x) return;
        if (!/=/.test(x)) { last = x; return; }
        const kv = /^flag(\d*p?\d*)=(.*)$/.exec(x);
        if (kv && last) { put(last, kv[2]); last = null; }
      });
    }
  }
}
// 3) Tracker (measured/flags-*.json, собраны по событиям карточек): «CC_DE» — страна аккаунта,
//    «GroupIdentity_GeoIdentity_wales» — флаг, который игрок выбрал сам. Страна аккаунта — раньше
//    Liquipedia, самовыбранный флаг — только там, где больше ничего нет.
const geoName = {};
{ const dn = new Intl.DisplayNames(['en'], { type: 'region' });
  for (const c of have) { if (!/^[a-z]{2}$/.test(c)) continue; let n; try { n = dn.of(c.toUpperCase()); } catch (e) { continue; } if (n) geoName[n.toLowerCase().replace(/[^a-z]/g, '')] = c; }
  Object.assign(geoName, { england: 'gb-eng', scotland: 'gb-sct', wales: 'gb-wls', unitedkingdom: 'gb', usa: 'us', unitedstatesofamerica: 'us', southkorea: 'kr', korea: 'kr', russia: 'ru', czechia: 'cz', czechrepublic: 'cz', turkey: 'tr', turkiye: 'tr', vietnam: 'vn', ivorycoast: 'ci' }); }
const flagFiles = fs.readdirSync(path.join(__dirname, 'measured')).filter(f => /^flags-.*\.json$/.test(f));
const cc = {}, geo = {}; let unknown = {};
for (const f of flagFiles) {
  let j = JSON.parse(fs.readFileSync(path.join(__dirname, 'measured', f), 'utf8')); if (typeof j === 'string') j = JSON.parse(j);
  for (const [nick, tok] of Object.entries(j)) {
    const k = String(nick).toLowerCase().trim();
    if (/^CC_/.test(tok)) { const v = norm(tok.slice(3)); if (v && !cc[k]) cc[k] = v; continue; }
    const g = /GeoIdentity_(.+)$/.exec(tok); if (!g) continue;
    const name = g[1].toLowerCase().replace(/[^a-z]/g, ''), v = geoName[name];
    if (v) { if (!geo[k]) geo[k] = v; } else unknown[name] = (unknown[name] || 0) + 1;
  }
}
const lq = Object.assign({}, out);
for (const k of Object.keys(out)) delete out[k];
Object.assign(out, geo, lq, cc);
console.log('tracker cc', Object.keys(cc).length, 'geo', Object.keys(geo).length, 'unknown geo', JSON.stringify(Object.entries(unknown).sort((a, b) => b[1] - a[1]).slice(0, 15)));
fs.writeFileSync(path.join(__dirname, 'liqui-flags.generated.js'),
  '// Generated by tools/build-liqui-flags.js — страна игрока по Liquipedia (там, где Tracker страны не дал).\nconst NAT_LIQUI=' + JSON.stringify(out) + ';\n');
console.log('handles', Object.keys(out).length);
