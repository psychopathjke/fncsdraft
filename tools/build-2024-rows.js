// FNCS 2024 card rows out of the Tracker harvest (21 September 2026).
//
// Input: tools/measured/tracker-2024-majors.json — for each Major (S28/S29/S30)
// and region (EU, NAC, BR, ASIA, ME, OCE — NA West did not exist in 2024) the
// boards of Open Qualifier 2 (last round, up to three pages), both Semi-Final
// brackets (round 3) and the Grand Final (two days, cumulative); and
// tools/measured/tracker-2024-gf-days.json — the Grand Final day boards, which
// carry wins and eliminations the cumulative board does not.
//
// Output: tools/2024-rows.generated.js with CARD_F<n><REG>_<Q|S|GF>_RAW arrays in
// the rowEntry shape the 2025 sets use — [rank, pts, matches, wins, avgElims,
// avgPlace, elimPts, name, name] — plus F<n>_NAT (handle -> country code).
//
//   node tools/build-2024-rows.js
'use strict';
const fs = require('fs'), path = require('path');
const H = JSON.parse(fs.readFileSync(path.join(__dirname, 'measured', 'tracker-2024-majors.json'), 'utf8'));
let GD = {}; try { GD = JSON.parse(fs.readFileSync(path.join(__dirname, 'measured', 'tracker-2024-gf-days.json'), 'utf8')); } catch (e) {}
const SETS = { S28: 'f1', S29: 'f2', S30: 'f3' };
const REGS = ['EU', 'NAC', 'BR', 'ASIA', 'ME', 'OCE'];
const KILL = { Q: 2, S: 4, GF: 4 };   // elim points per stage, off the windows' scoring rules
const q = s => JSON.stringify(String(s));
const out = [];
const nat = { f1: {}, f2: {}, f3: {} };
const rowsOf = (board, dayBoards) => {
  const rows = [].concat(...(board.pages || []));
  const byKey = new Map();
  (dayBoards || []).forEach(b => (b.rows || []).forEach(r => { const k = r.names.map(n => String(n).toLowerCase()).sort().join('|'); const cur = byKey.get(k) || { wins: 0, elims: 0 }; cur.wins += r.wins; cur.elims += r.elims; byKey.set(k, cur); }));
  return rows.map(r => {
    const k = r.names.map(n => String(n).toLowerCase()).sort().join('|');
    const extra = byKey.get(k);
    const wins = extra ? extra.wins : r.wins, elims = extra ? extra.elims : r.elims;
    const matches = Math.max(r.matches || 0, 1);
    return { rank: r.rank, pts: r.pts, matches, wins, avgElims: +(elims / matches).toFixed(2), avgPlace: r.avgPlace == null ? 0 : r.avgPlace, elimPts: 0, names: r.names, cc: r.cc };
  });
};
for (const [season, set] of Object.entries(SETS)) {
  for (const reg of REGS) {
    const Q = H[season + '|' + reg + '|Q'], SU = H[season + '|' + reg + '|SU'], SL = H[season + '|' + reg + '|SL'], G = H[season + '|' + reg + '|G'];
    if (!Q || !SU || !SL || !G) { console.log('missing', season, reg); continue; }
    const stages = {
      Q: rowsOf(Q),
      // one Semi-Final board: the upper bracket first, the lower after it, ranks re-numbered
      S: [].concat(rowsOf(SU), rowsOf(SL)).map((r, i) => Object.assign({}, r, { rank: i + 1 })),
      GF: rowsOf(G, [GD[season + '|' + reg + '|GD1'], GD[season + '|' + reg + '|GD2']].filter(Boolean))
    };
    for (const st of ['Q', 'S', 'GF']) {
      const rows = stages[st];
      rows.forEach(r => { r.elimPts = Math.round(r.avgElims * r.matches * KILL[st]); r.names.forEach((n, i) => { if (r.cc && r.cc[i] && !nat[set][n]) nat[set][n] = String(r.cc[i]).toLowerCase(); }); });
      out.push('const CARD_' + set.toUpperCase() + reg + '_' + st + '_RAW=[');
      out.push(rows.map(r => '[' + [r.rank, r.pts, r.matches, r.wins, r.avgElims, r.avgPlace, r.elimPts].join(',') + ',' + r.names.map(q).join(',') + ']').join(',\n'));
      out.push('];');
    }
  }
}
for (const set of Object.keys(nat)) out.push('const ' + set.toUpperCase() + '_NAT=' + JSON.stringify(nat[set]) + ';');
fs.writeFileSync(path.join(__dirname, '2024-rows.generated.js'), '// Generated by tools/build-2024-rows.js — FNCS 2024 (duos), six regions, from tools/measured/.\n' + out.join('\n') + '\n');
const n = out.filter(l => /^const CARD_/.test(l)).length;
console.log('tables', n, 'nat', Object.keys(nat.f1).length, Object.keys(nat.f2).length, Object.keys(nat.f3).length);
