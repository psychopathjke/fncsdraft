// Капы, выплаты и Invitational 2022-го из tools/measured/tracker-2022-{cups,fncs}.json и
// liqui-2022/ (Invitational). Выход — tools/2022-cal.generated.js:
// CC_VICTORY_2022, CC_DCC_PAY_2022, CC_MAJOR_PAY_2022, CC_WF_PAY_2022, INV2022_DUOS,
// INV2022_SEATS, INV2022_PRIZES.
//   node tools/build-2022-cal.js
'use strict';
const fs = require('fs'), path = require('path');
const M = path.join(__dirname, 'measured');
const cups = JSON.parse(fs.readFileSync(path.join(M, 'tracker-2022-cups.json'), 'utf8'));
const fncs = JSON.parse(fs.readFileSync(path.join(M, 'tracker-2022-fncs.json'), 'utf8'));
const REGS = ['EU', 'NAC', 'NAW', 'BR', 'ASIA', 'ME', 'OCE'];
const src = r => r === 'NAC' ? 'NAE' : r;
const day = w => String(w.begin).slice(0, 10);
const table = usd => usd.slice().sort((a, b) => a[0] - b[0]);
const out = [];
// ---- капы (дни — Европа): событие = день раунда 1 ----
const V = [];
const add = (slug, mode, name, pay) => {
  const byEvent = new Map();
  (cups[slug + '|EU'] || []).forEach(w => { const m = /Event(\d+)_?Round1/.exec(w.id); if (!m) return; const cur = byEvent.get(m[1]); if (!cur || day(w) < day(cur)) byEvent.set(m[1], w); });
  [...byEvent.values()].forEach(w => V.push({ day: day(w), id: slug, mode, n: 0, name, pay }));
};
[['S19', 'S19'], ['S20', 'S20'], ['S21', 'S21']].forEach(([s]) => {
  add(s + '_DuosCashCup', 'duo', 'Duos Cash Cup', s);
  add(s + '_SoloCashCup', 'solo', 'Solo Cash Cup', s + 'SOLO');
});
V.sort((a, b) => a.day < b.day ? -1 : a.day > b.day ? 1 : 0);
const seq = {}; V.forEach(v => { seq[v.id] = (seq[v.id] || 0) + 1; v.n = seq[v.id]; });
out.push('const CC_VICTORY_2022=[');
out.push(V.map(v => '  ' + JSON.stringify(v).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'")).join(',\n'));
out.push('];');
// ---- выплаты кэш-капов по сезону и региону (раунд 2, на игрока) ----
const dcc = {};
const payOf = (slug, reg) => { const w = (cups[slug + '|' + reg] || []).find(x => x.usd && x.usd.length); return w ? table(w.usd) : null; };
['S19', 'S20', 'S21'].forEach(s => {
  dcc[s] = {}; dcc[s + 'SOLO'] = {};
  REGS.forEach(r => {
    const d = payOf(s + '_DuosCashCup', src(r)); if (d) dcc[s][r] = d;
    const o = payOf(s + '_SoloCashCup', src(r)); if (o) dcc[s + 'SOLO'][r] = o;
  });
});
out.push('const CC_DCC_PAY_2022=' + JSON.stringify(dcc).replace(/"(\w+)":/g, '$1:') + ';');
// ---- финалы сезонов (на игрока) ----
const maj = {};
[[1, 'S19'], [2, 'S20'], [3, 'S21']].forEach(([n, s]) => {
  maj[n] = {};
  REGS.forEach(r => { const b = fncs[s + '_FNCS_Finals|' + src(r) + '|Finals_Round2']; if (b && b.usd && b.usd.length) maj[n][r] = table(b.usd); });
});
out.push('const CC_MAJOR_PAY_2022=' + JSON.stringify(maj).replace(/"(\w+)":/g, '$1:') + ';');
// ---- финал недели Elite (C3S4) ----
const wf = {};
REGS.forEach(r => { const t = payOf('S22_DivisionalCups_Elite_Finals', src(r)); if (t) wf[r] = t; });
out.push('const CC_WF_PAY_2022=' + JSON.stringify(wf).replace(/"(\w+)":/g, '$1:') + ';');
// ---- Invitational: 50 дуо по местам (Liquipedia), регион — по таблицам Tracker ----
const regOf = {};
Object.keys(fncs).forEach(k => { let reg = k.split('|')[1]; if (reg === 'NAE') reg = 'NAC'; (fncs[k].rows || []).forEach(r => r[6].forEach(n => { const h = String(n).toLowerCase(); if (!regOf[h]) regOf[h] = reg; })); });
const liq = fs.readFileSync(path.join(M, 'liqui-2022', 'Fortnite Champion Series__2022__Invitational.txt'), 'utf8');
const duos = [], prizes = {};
const re = /\{\{prize pool slot duos\s*\|([^}]*)\}\}/g; let m;
while ((m = re.exec(liq))) {
  const parts = m[1].split('|').map(x => x.trim());
  const place = +((parts.find(x => /^place=/.test(x)) || '').split('=')[1] || 0);
  const usd = +((parts.find(x => /^usdprize=/.test(x)) || '').split('=')[1] || '0').replace(/,/g, '');
  const names = parts.filter(x => x && !/=/.test(x)).slice(0, 2);
  if (!place || names.length < 2) continue;
  duos.push(names); prizes[place] = usd;
}
const seats = {};
duos.forEach(d => { const reg = d.map(n => regOf[String(n).toLowerCase()]).find(Boolean) || '?'; seats[reg] = (seats[reg] || 0) + 1; });
out.push('const INV2022_DUOS=' + JSON.stringify(duos) + ';');
out.push('const INV2022_SEATS=' + JSON.stringify(seats).replace(/"(\w+)":/g, '$1:').replace(/"\?":/g, "'?':") + ';');
out.push('const INV2022_PRIZES=' + JSON.stringify(prizes) + ';');
fs.writeFileSync(path.join(__dirname, '2022-cal.generated.js'), '// Generated by tools/build-2022-cal.js — капы, выплаты и Invitational FNCS 2022.\n' + out.join('\n') + '\n');
console.log('cups', V.length, 'dcc', Object.keys(dcc).map(k => k + ':' + Object.keys(dcc[k]).length).join(' '), 'majors', Object.keys(maj).map(n => n + ':' + Object.keys(maj[n]).length).join(' '), 'wf', Object.keys(wf).length, 'inv', duos.length, JSON.stringify(seats), 'prize1', prizes[1]);
