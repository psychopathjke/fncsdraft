// FNCS 2023 card rows out of the Tracker harvest.
//
// Input: tools/measured/tracker-2023-{S23,S24S25,NAC}.json — per Major and region the
// Day 2 boards of the three weeks (up to 200 duos), the three week Finals (50) and the
// Surge Week (50), and both Grand Final days (50).
//
// Output: tools/2023-rows.generated.js with CARD_E<n><REG>_<Q|S|GF>_RAW arrays in the
// rowEntry shape — [rank, pts, matches, wins, avgElims, avgPlace, elimPts, name, name] —
// plus E<n>_NAT (handle -> country code). Stages, as the 2024 sets read them:
//   Q  (L) — the three weeks' Day 2, each duo once, at its best evening;
//   S  (P) — the three week Finals and the Surge Week, each duo once, at its best;
//   GF (G) — the Grand Final, both days summed.
// Major 1 had NA East and NA West; from Major 2 on it was one NA Central. NA East is
// NAC, and NA West's Major 1 duos join NAC too — that is where they played afterwards.
//
//   node tools/build-2023-rows.js
'use strict';
const fs = require('fs'), path = require('path');
const M = path.join(__dirname, 'measured');
const H = Object.assign({},
  JSON.parse(fs.readFileSync(path.join(M, 'tracker-2023-S23.json'), 'utf8')),
  JSON.parse(fs.readFileSync(path.join(M, 'tracker-2023-S24S25.json'), 'utf8')),
  JSON.parse(fs.readFileSync(path.join(M, 'tracker-2023-NAC.json'), 'utf8')));
const SETS = { e1: 'S23_FNCS_Major1', e2: 'S24_FNCS_Major2', e3: 'S25_FNCS_Major3' };
const REGS = ['EU', 'NAC', 'BR', 'ASIA', 'ME', 'OCE'];
const SRC_REGS = { NAC: ['NAC', 'NAE', 'NAW'] };
const KILL = { Q: 2, S: 4, GF: 4 };
const q = s => JSON.stringify(String(s));
const keyOf = names => names.map(n => String(n).toLowerCase()).sort().join('|');
const boards = (prefix, reg, re) => Object.keys(H).filter(k => k.startsWith(prefix) && k.split('|')[1] === reg && re.test(k.split('|')[2]) && H[k].rows).map(k => H[k]);
// Each duo once, at its best evening (points), then re-ranked.
const best = list => {
  const by = new Map();
  list.forEach(b => b.rows.forEach(r => { const k = keyOf(r[6]); const cur = by.get(k); if (!cur || r[1] > cur[1]) by.set(k, r); }));
  return [...by.values()].sort((a, b) => b[1] - a[1]).map((r, i) => [i + 1].concat(r.slice(1)));
};
// Both Grand Final days summed per duo.
const summed = list => {
  const by = new Map();
  list.forEach(b => b.rows.forEach(r => {
    const k = keyOf(r[6]); const cur = by.get(k);
    if (!cur) { by.set(k, { pts: r[1], m: r[2], w: r[3], e: r[4], pl: r[5] * r[2], names: r[6], cc: r[7] }); return; }
    cur.pts += r[1]; cur.m += r[2]; cur.w += r[3]; cur.e += r[4]; cur.pl += r[5] * r[2];
  }));
  return [...by.values()].sort((a, b) => b.pts - a.pts)
    .map((t, i) => [i + 1, t.pts, t.m, t.w, t.e, t.m ? +(t.pl / t.m).toFixed(2) : 0, t.names, t.cc]);
};
const out = [], nat = {};
for (const [set, prefix] of Object.entries(SETS)) {
  nat[set] = {};
  for (const reg of REGS) {
    const src = SRC_REGS[reg] || [reg];
    // Regions are ranked one after another, never mixed by points: NA West was the
    // thinner room, so its Major 1 winners stand below the whole of NA East.
    const stage = (re, fold) => {
      const seen = new Set(), rows = [];
      src.forEach(r => fold(boards(prefix, r, re)).forEach(x => { const k = keyOf(x[6]); if (seen.has(k)) return; seen.add(k); rows.push(x); }));
      return rows.map((x, i) => [i + 1].concat(x.slice(1)));
    };
    const stages = {
      Q: stage(/Week\d_Day2$/, best),
      // Surge Week is left out: its board adds up a whole week of games (~1200 points
      // against ~350 in a week Final), and whoever came through it is in the Grand Final.
      S: stage(/Week\d_Finals$/, best),
      GF: stage(/GrandFinals_Day[12]$/, summed)
    };
    if (!stages.GF.length) { console.log('no Grand Final', set, reg); continue; }
    for (const st of ['Q', 'S', 'GF']) {
      const rows = stages[st];
      rows.forEach(r => r[6].forEach((n, i) => { if (r[7] && r[7][i] && !nat[set][n]) nat[set][n] = String(r[7][i]).toLowerCase(); }));
      out.push('const CARD_' + set.toUpperCase() + reg + '_' + st + '_RAW=[');
      out.push(rows.map(r => {
        const m = Math.max(r[2] || 0, 1), avgElims = +(r[4] / m).toFixed(2);
        return '[' + [r[0], r[1], m, r[3], avgElims, r[5] || 0, Math.round(r[4] * KILL[st])].join(',') + ',' + r[6].map(q).join(',') + ']';
      }).join(',\n'));
      out.push('];');
      console.log(set, reg, st, rows.length, rows[0] ? rows[0][6].join('+') : '');
    }
  }
}
for (const set of Object.keys(nat)) out.push('const ' + set.toUpperCase() + '_NAT=' + JSON.stringify(nat[set]) + ';');
fs.writeFileSync(path.join(__dirname, '2023-rows.generated.js'), '// Generated by tools/build-2023-rows.js — FNCS 2023 (duos), six regions, from tools/measured/.\n' + out.join('\n') + '\n');
console.log('tables', out.filter(l => /^const CARD_/.test(l)).length);
