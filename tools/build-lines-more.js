// Дополнительные реплики (личка и реплаи под постами) — отдельным файлом lines-more.js рядом с index.html.
// Отдельно, а не в index.html: 127 КБ на пять языков сдвинули бы app.js за стоп-линию 9 МБ (см. память про ёмкость);
// файл грузится с defer — после разбора страницы, не задерживая старт. Тег <script src="lines-more.js?v=…" defer>
// в index.html, ?v= — sha1 файла, как у zone-sim.js/mp.js (check-deploy-folder).
// Вход: tools/measured/lines-more/<язык>.json вида {dm:{ключ:[…]}, co:{ccCoX:[…]}}.
// Проверяет: ключ существует, метки только {aN} {topN} {TopN} {dateN} и N меньше числа аргументов исходной
// реплики, других фигурных скобок нет. Плохая строка выбрасывается с предупреждением.
//   node tools/build-lines-more.js
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.resolve(__dirname, '..'), DIR = path.join(__dirname, 'measured', 'lines-more');
const F = path.join(ROOT, 'index.html'), OUTJS = path.join(ROOT, 'lines-more.js');
let src = fs.readFileSync(F, 'utf8');
// Число аргументов исходной реплики: «ключ:(a,b)=>» или «ключ:a=>».
const argc = key => {
  const m = src.match(new RegExp('[{,\\s]' + key + ':\\s*(\\(([^)]*)\\)|([A-Za-z_$][\\w$]*))\\s*=>'));
  if (!m) return src.indexOf(key + ':') >= 0 ? 0 : -1;
  return m[2] != null ? m[2].split(',').filter(x => x.trim()).length : 1;
};
const out = {}, warn = [];
for (const lang of ['ru', 'en', 'fr', 'it', 'pt']) {
  const f = path.join(DIR, lang + '.json');
  if (!fs.existsSync(f)) { warn.push(lang + ': файла нет'); continue; }
  const j0 = JSON.parse(fs.readFileSync(f, 'utf8'));
  const res = { dm: {}, co: {} };
  let n = 0;
  for (const [k, arr] of Object.entries(j0.dm || {})) {
    const ac = argc(k);
    if (ac < 0) { warn.push(lang + ' ' + k + ': ключа нет'); continue; }
    const ok = (arr || []).filter(s => {
      if (typeof s !== 'string' || !s.trim()) return false;
      const bad = s.replace(/\{(a|top|Top|date)(\d)\}/g, (m, t, d) => (+d < ac ? '' : '\u0000'));
      if (/[{}\u0000]/.test(bad)) { warn.push(lang + ' ' + k + ': метка мимо — ' + s); return false; }
      return true;
    });
    if (ok.length) { res.dm[k] = ok; n += ok.length; }
  }
  for (const [k, arr] of Object.entries(j0.co || {})) {
    if (!/^ccCo[A-Z]/.test(k)) continue;
    const ok = (arr || []).filter(s => typeof s === 'string' && s.trim() && !/[{}]/.test(s));
    if (ok.length) { res.co[k] = ok; n += ok.length; }
  }
  out[lang] = res;
  console.log(lang + ': ' + Object.keys(res.dm).length + ' реплик лички, ' + Object.keys(res.co).length + ' пулов, строк ' + n);
}
const js = '/* Generated by tools/build-lines-more.js — дополнительные реплики (личка и реплаи), см. ccText и L() в index.html. */\n' +
  'var CC_LINES_MORE=' + JSON.stringify(out) + ';\n' +
  // Словари языков собираются лениво (L()); собранные до этого файла — пересобрать, чтобы пулы реплаев подросли.
  'try{ CC_L_CACHE={}; }catch(e){}\n';
fs.writeFileSync(OUTJS, js);
const v = crypto.createHash('sha1').update(fs.readFileSync(OUTJS)).digest('hex').slice(0, 8);
// В index.html данных больше нет: пустой объект, который файл потом заменит.
const A = '// ==== CC_LINES_MORE (tools/build-lines-more.js) ====', B = '// ==== /CC_LINES_MORE ====';
const i = src.indexOf(A), j = src.indexOf(B);
if (i < 0 || j < 0) throw new Error('метки CC_LINES_MORE не найдены');
src = src.slice(0, i) + A + '\nvar CC_LINES_MORE=(typeof CC_LINES_MORE!==\'undefined\' && CC_LINES_MORE) || {};\n' + src.slice(j);
// Тег скрипта с версией.
const tag = /<script src="lines-more\.js\?v=[0-9a-f]+" defer><\/script>/;
const newTag = '<script src="lines-more.js?v=' + v + '" defer></script>';
if (tag.test(src)) src = src.replace(tag, newTag);
else {
  const anchor = '<script src="mp.js?v=';
  const k = src.indexOf(anchor); if (k < 0) throw new Error('нет тега mp.js — некуда поставить lines-more.js');
  const end = src.indexOf('</script>', k) + '</script>'.length;
  src = src.slice(0, end) + '\n<!-- Дополнительные реплики лички и реплаев (tools/build-lines-more.js), грузятся после страницы. -->\n' + newTag + src.slice(end);
}
fs.writeFileSync(F, src);
console.log('lines-more.js ' + fs.statSync(OUTJS).size + ' байт, ?v=' + v);
if (warn.length) console.log('предупреждения (' + warn.length + '):\n  ' + warn.slice(0, 30).join('\n  '));
