// Капы и выплаты 2019-го из tools/measured/tracker-2019.json. Выход — tools/2019-cal.generated.js:
// CC_VICTORY_2019 (трио Cash Cup сезона X), CC_DCC_PAY_2019, CC_MX_PAY_2019 (финалы: 3 — FNCS X,
// 4 — FNCS C2S1, на игрока; World Cup — WC2019_PAY из build-2019-rows.js).
//   node tools/build-2019-cal.js
'use strict';
const fs = require('fs'), path = require('path');
let H = JSON.parse(fs.readFileSync(path.join(__dirname, 'measured', 'tracker-2019.json'), 'utf8'));
if (typeof H === 'string') H = JSON.parse(H);
const REGS = ['EU', 'NAC', 'NAW', 'BR', 'ASIA', 'ME', 'OCE'];
const src = r => r === 'NAC' ? 'NAE' : r;
const obj = o => JSON.stringify(o).replace(/"(\w+)":/g, '$1:');
const out = [];
const V = (H['S10_CC_Trios|EU'] || []).map((w, i) => ({ day: w.begin, id: 'S10_CC_Trios', mode: 'trio', n: i + 1, name: 'Trios Cash Cup', pay: 'S10' }));
out.push('const CC_VICTORY_2019=[');
out.push(V.map(v => '  ' + JSON.stringify(v).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'")).join(',\n'));
out.push('];');
const dcc = { S10: {} };
REGS.forEach(r => { const w = (H['S10_CC_Trios|' + src(r)] || []).find(x => x.usd && x.usd.length); if (w) dcc.S10[r] = w.usd; });
out.push('const CC_DCC_PAY_2019=' + obj(dcc) + ';');
const pay = { 3: {}, 4: {} };
REGS.forEach(r => {
  const a = H['S10_FNCS_Finals|' + src(r) + '|Finals_Event5']; if (a && a.usd && a.usd.length) pay[3][r] = a.usd;
  const b = H['S11_FNCS_Finals|' + src(r) + '|Finals_Event5']; if (b && b.usd && b.usd.length) pay[4][r] = b.usd;
});
out.push('const CC_MX_PAY_2019=' + obj(pay) + ';');
fs.writeFileSync(path.join(__dirname, '2019-cal.generated.js'), '// Generated by tools/build-2019-cal.js — капы и выплаты 2019-го.\n' + out.join('\n') + '\n');
console.log('cups', V.length, 'pay3', Object.keys(pay[3]).join(','), 'pay4', Object.keys(pay[4]).join(','), JSON.stringify((pay[3].EU || []).slice(0, 3)));
