// Сторож мерил урон в минуту НЕ ТАМ, где его показывает доска.
//
// ccStatLeaders считает дроби — соотношение урона и урон в минуту — только
// среди проживших не меньше среднего по лобби, потому что максимум дроби иначе
// достаётся рано умершему с удачной перестрелкой. Проба применяла этот отбор
// только к соотношению, а урон в минуту брала по всему лобби — и годами
// показывала красным число, которого на доске не бывает.
const fs=require('fs'), path=require('path');
const F=path.join(__dirname,'check-matchstats-real.js');
let s=fs.readFileSync(F,'utf8');
const A='\'o={dmg:top("dmg"), dpm:top("dpm"),';
if(s.split(A).length!==2) throw new Error('строка сборки лидеров не найдена');
s=s.replace(A, '\'o={dmg:top("dmg"), dpm:top("dpm", deep),');
const B='  // Дроби — только среди проживших не меньше среднего, тем же отбором, каким их';
if(s.split(B).length!==2) throw new Error('комментарий про дроби не найден');
s=s.replace(B, '  // Дроби — и соотношение урона, и урон в минуту — только среди проживших не' +
  (s.indexOf('\r\n')>=0?'\r\n':'\n') + '  // меньше среднего, тем же отбором, каким их');
fs.writeFileSync(F,s);
